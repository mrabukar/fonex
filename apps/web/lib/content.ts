const COLOR_FAMILY_KEYS = Object.keys(colorFamilies);

export function colorFamilyForId(id: string): string {
  let hash = 0;
  for (let i = 0; i < id.length; i++) hash += id.charCodeAt(i);
  return COLOR_FAMILY_KEYS[hash % COLOR_FAMILY_KEYS.length];
}

